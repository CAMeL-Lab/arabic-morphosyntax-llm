def _common_data_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("task", choices=TASKS)
    parser.add_argument("--input", type=Path, required=True, help="Input JSONL")
    parser.add_argument("--demonstrations", type=Path, help="Gold demonstration JSONL")
    parser.add_argument("--shots", type=int, default=0)
    parser.add_argument("--retrieval", choices=RETRIEVAL_METHODS, default="chrf-high")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--embedding-model", default=DEFAULT_MODEL)
    parser.add_argument("--embedding-device", help="PyTorch device (default: CUDA if available, else CPU)")
    parser.add_argument("--embedding-batch-size", type=int, default=32)
    parser.add_argument("--embedding-max-length", type=int, default=256)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="arabic-morphosyntax",
        description="Arabic morphosyntactic tagging and dependency parsing with LLMs",
    )
    parser.add_argument("--config", type=Path, help="Alternative model-profile YAML")
    subparsers = parser.add_subparsers(dest="command", required=True)

    subparsers.add_parser("models", help="List configured paper models")

    render = subparsers.add_parser("render", help="Render prompts without calling a model")
    _common_data_arguments(render)
    render.add_argument("--output", type=Path, required=True)
    render.add_argument("--limit", type=int, default=0, help="0 renders every input")
    render.add_argument("--overwrite", action="store_true")

    shots = subparsers.add_parser("shots", help="Generate a reusable shot selection map")
    _common_data_arguments(shots)
    shots.add_argument("--output", type=Path, required=True)
    shots.add_argument("--overwrite", action="store_true")

    run = subparsers.add_parser("run", help="Run a paper benchmark task")
    _common_data_arguments(run)
    run.add_argument("--model", required=True, help="Model-profile key")
    run.add_argument("--shot-map", type=Path, help="Selections generated by the shots command")
    run.add_argument("--output", type=Path, required=True)
    run.add_argument("--base-url", help="Override a vLLM/OpenAI-compatible endpoint")
    run.add_argument("--model-id", help="Override the configured provider model ID")
    run.add_argument("--temperature", type=float, default=argparse.SUPPRESS)
    run.add_argument("--max-output-tokens", type=int, default=argparse.SUPPRESS)
    run.add_argument("--reasoning-effort", default=argparse.SUPPRESS)
    run.add_argument("--concurrency", type=int, default=1)
    run.add_argument("--retries", type=int, default=2, help="Retries after the first attempt")
    run.add_argument("--checkpoint-every", type=int, default=10)
    output_mode = run.add_mutually_exclusive_group()
    output_mode.add_argument("--resume", action="store_true")
    output_mode.add_argument("--overwrite", action="store_true")

    evaluate = subparsers.add_parser("evaluate", help="Score PATB morphology")
    evaluate.add_argument("task", choices=("morphology", "cascade"))
    evaluate.add_argument("--predictions", type=Path, required=True)
    evaluate.add_argument("--gold", type=Path, required=True)
    evaluate.add_argument("--output", type=Path, help="Optional JSON metrics file")
    evaluate.add_argument("--overwrite", action="store_true")

    export = subparsers.add_parser("export-conll", help="Convert LLM parses for upstream CAMeL CoNLL")
    export.add_argument("--predictions", type=Path, required=True)
    export.add_argument("--output", type=Path, required=True)
    export.add_argument("--overwrite", action="store_true")

    convert = subparsers.add_parser("convert", help="Convert treebank files to JSONL")
    convert.add_argument(
        "kind", choices=("patb-tsv", "catib-conllu")
    )
    convert.add_argument("--input", type=Path, required=True)
    convert.add_argument("--output", type=Path, required=True)
    convert.add_argument("--overwrite", action="store_true")

    merge = subparsers.add_parser("merge-gold", help="Merge aligned gold JSONL views by ID")
    merge.add_argument("--inputs", type=Path, nargs="+", required=True)
    merge.add_argument("--output", type=Path, required=True)
    merge.add_argument("--overwrite", action="store_true")

    return parser


def _load_data(args: argparse.Namespace) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    records = [normalize_input(record, args.task) for record in read_jsonl(args.input)]
    demonstrations: list[dict[str, Any]] = []
    if args.demonstrations:
        demonstrations = [
            normalize_input(record, args.task) for record in read_jsonl(args.demonstrations)
        ]
    if args.shots < 0:
        raise ValueError("--shots cannot be negative")
    if args.shots and not demonstrations:
        raise ValueError("--shots requires --demonstrations")
    if (args.shots and args.retrieval.startswith("cosine")
            and not getattr(args, "shot_map", None)):
        embed_records(
            records, demonstrations, task=args.task,
            model_name=args.embedding_model, device=args.embedding_device,
            batch_size=args.embedding_batch_size, max_length=args.embedding_max_length,
        )
    return records, demonstrations


def _profile(args: argparse.Namespace, profiles: dict[str, ModelProfile]) -> ModelProfile:
    if args.model not in profiles:
        raise ValueError(f"Unknown model {args.model!r}; choose from {', '.join(profiles)}")
    return profiles[args.model].with_overrides(
        model_id=args.model_id,
        base_url=args.base_url,
        temperature=getattr(args, "temperature", None),
        max_output_tokens=getattr(args, "max_output_tokens", None),
        reasoning_effort=getattr(args, "reasoning_effort", None),
        override_temperature=hasattr(args, "temperature"),
        override_max_output_tokens=hasattr(args, "max_output_tokens"),
        override_reasoning_effort=hasattr(args, "reasoning_effort"),
    )


def _models(profiles: dict[str, ModelProfile]) -> int:
    rows = [
        {
            "key": profile.key,
            "display_name": profile.display_name,
            "provider": profile.provider,
            "model_id": profile.model_id,
            "base_url": profile.base_url,
        }
        for profile in profiles.values()
    ]
    print(json.dumps(rows, ensure_ascii=False, indent=2))
    return 0


def _render(args: argparse.Namespace) -> int:
    if args.output.exists() and not args.overwrite:
        raise FileExistsError(f"{args.output} exists; pass --overwrite")
    records, demonstrations = _load_data(args)
    if args.limit > 0:
        records = records[: args.limit]
    rows = []
    for record in records:
        selection = select_demonstrations(
            record,
            demonstrations,
            task=args.task,
            shots=args.shots,
            method=args.retrieval,
            seed=args.seed,
        )
        rows.append(
            {
                "id": record["id"],
                "task": args.task,
                "demonstrations": selection.metadata,
                "requests": render_requests(
                    task=args.task,
                    record=record,
                    selection=selection,
                ),
            }
        )
    write_jsonl_atomic(args.output, rows)
    print(f"Rendered {len(rows)} input(s) to {args.output}")
    return 0


def _shots(args: argparse.Namespace) -> int:
    if args.output.exists() and not args.overwrite:
        raise FileExistsError(f"{args.output} exists; pass --overwrite")
    records, demonstrations = _load_data(args)
    rows = []
    for record in records:
        selection = select_demonstrations(
            record, demonstrations, task=args.task, shots=args.shots,
            method=args.retrieval, seed=args.seed,
        )
        rows.append({"id": record["id"], "shots": selection.metadata})
    write_jsonl_atomic(args.output, rows)
    print(f"Selected shots for {len(rows)} input(s) to {args.output}")
    return 0


def _existing_results(args: argparse.Namespace, profile: ModelProfile) -> dict[str, dict[str, Any]]:
    if not args.output.exists():
        return {}
    if not args.resume:
        if args.overwrite:
            return {}
        raise FileExistsError(f"{args.output} exists; pass --resume or --overwrite")
    rows = read_jsonl(args.output)
    existing: dict[str, dict[str, Any]] = {}
    for row in rows:
        if row.get("task") != args.task or row.get("model") != profile.key:
            raise ValueError(
                f"{args.output} contains a different task/model and cannot be resumed"
            )
        if row.get("status") == "ok":
            existing[str(row["id"])] = row
    return existing


async def _run_async(
    args: argparse.Namespace,
    profile: ModelProfile,
    records: list[dict[str, Any]],
    demonstrations: list[dict[str, Any]],
) -> int:
    if args.concurrency < 1 or args.retries < 0 or args.checkpoint_every < 1:
        raise ValueError("concurrency/checkpoint-every must be positive and retries nonnegative")
    completed = _existing_results(args, profile)
    pending = [record for record in records if record["id"] not in completed]
    if not pending:
        ordered = [completed[record["id"]] for record in records]
        write_jsonl_atomic(args.output, ordered)
        print(f"All {len(records)} input(s) are already complete in {args.output}")
        return 0
    provider = create_provider(profile)
    pipeline = TaskPipeline(
        provider=provider,
        profile=profile,
        task=args.task,
        demonstrations=demonstrations,
        shots=args.shots,
        retrieval_method=args.retrieval,
        seed=args.seed,
        retries=args.retries,
        shot_map=read_jsonl(args.shot_map) if args.shot_map else None,
    )
    semaphore = asyncio.Semaphore(args.concurrency)

    async def predict(record: dict[str, Any]) -> dict[str, Any]:
        async with semaphore:
            try:
                return await pipeline.predict(record)
            except Exception as error:
                return {
                    "id": record["id"],
                    "task": args.task,
                    "model": profile.key,
                    "model_id": profile.model_id,
                    "configuration": {
                        "provider": profile.provider,
                        "base_url": profile.base_url,
                        "generation": {
                            "temperature": profile.generation.temperature,
                            "seed": profile.generation.seed,
                            "max_output_tokens": profile.generation.max_output_tokens,
                            "reasoning_effort": profile.generation.reasoning_effort,
                        },
                        "provider_options": profile.provider_options,
                    },
                    "status": "error",
                    "input": {
                        key: record[key] for key in ("id", "text", "tokens") if key in record
                    },
                    "prediction": None,
                    "demonstrations": [],
                    "calls": [],
                    "error": f"{type(error).__name__}: {error}",
                }

    try:
        tasks = [asyncio.create_task(predict(record)) for record in pending]
        since_checkpoint = 0
        for future in asyncio.as_completed(tasks):
            row = await future
            completed[row["id"]] = row
            since_checkpoint += 1
            if since_checkpoint >= args.checkpoint_every:
                ordered = [
                    completed[record["id"]]
                    for record in records
                    if record["id"] in completed
                ]
                write_jsonl_atomic(args.output, ordered)
                since_checkpoint = 0
        ordered = [completed[record["id"]] for record in records if record["id"] in completed]
        write_jsonl_atomic(args.output, ordered)
    finally:
        await provider.close()

    errors = sum(row.get("status") != "ok" for row in completed.values())
    print(
        f"Completed {len(completed)}/{len(records)} input(s) with {errors} error(s); "
        f"results: {args.output}"
    )
    return 1 if errors else 0


def _run(args: argparse.Namespace, profiles: dict[str, ModelProfile]) -> int:
    records, demonstrations = _load_data(args)
    profile = _profile(args, profiles)
    return asyncio.run(_run_async(args, profile, records, demonstrations))


def _evaluate(args: argparse.Namespace) -> int:
    metrics = evaluate_outputs(
        task=args.task,
        predictions=read_jsonl(args.predictions),
        gold=read_jsonl(args.gold),
    )
    rendered = json.dumps(metrics, ensure_ascii=False, indent=2) + "\n"
    if args.output:
        if args.output.exists() and not args.overwrite:
            raise FileExistsError(f"{args.output} exists; pass --overwrite")
        args.output.parent.mkdir(parents=True, exist_ok=True)
        temporary = args.output.with_name(f".{args.output.name}.tmp")
        temporary.write_text(rendered, encoding="utf-8")
        temporary.replace(args.output)
        print(f"Wrote metrics to {args.output}")
    else:
        print(rendered, end="")
    return 0


def _export_conll(args: argparse.Namespace) -> int:
    if args.output.exists() and not args.overwrite:
        raise FileExistsError(f"{args.output} exists; pass --overwrite")
    predictions_to_conll(read_jsonl(args.predictions), args.output)
    print(f"Wrote CoNLL predictions to {args.output}")
    return 0


def _write_new_jsonl(path: Path, rows: list[dict[str, Any]], overwrite: bool) -> None:
    if path.exists() and not overwrite:
        raise FileExistsError(f"{path} exists; pass --overwrite")
    write_jsonl_atomic(path, rows)


def _convert(args: argparse.Namespace) -> int:
    if args.kind == "patb-tsv":
        rows = convert_patb_tsv(args.input)
    else:
        rows = convert_conllu(args.input, kind=args.kind)
    _write_new_jsonl(args.output, rows, args.overwrite)
    print(f"Converted {len(rows)} sentence(s) to {args.output}")
    return 0


def _merge_gold(args: argparse.Namespace) -> int:
    rows = merge_gold_files([read_jsonl(path) for path in args.inputs])
    _write_new_jsonl(args.output, rows, args.overwrite)
    print(f"Merged {len(rows)} sentence(s) to {args.output}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        profiles = load_profiles(args.config)
        if args.command == "models":
            return _models(profiles)
        if args.command == "render":
            return _render(args)
        if args.command == "shots":
            return _shots(args)
        if args.command == "run":
            return _run(args, profiles)
        if args.command == "evaluate":
            return _evaluate(args)
        if args.command == "export-conll":
            return _export_conll(args)
        if args.command == "convert":
            return _convert(args)
        if args.command == "merge-gold":
            return _merge_gold(args)
        parser.error(f"Unsupported command {args.command}")
    except (OSError, RuntimeError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
